// Shared XML helpers for the Exchange Format importer/exporter. DOM only, no regex parsing.
import type { PreservedAttr, PreservedChild, PreservedXml } from '../../../core/model/types';

/** Verified in schemas/archimate3_Model.xsd: the 3.1 schemas keep the 3.0 namespace URI. */
export const NS = 'http://www.opengroup.org/xsd/archimate/3.0/';
export const XSI_NS = 'http://www.w3.org/2001/XMLSchema-instance';
export const XML_NS = 'http://www.w3.org/XML/1998/namespace';
export const XMLNS_NS = 'http://www.w3.org/2000/xmlns/';
export const DEFAULT_SCHEMA_LOCATION =
  NS + ' http://www.opengroup.org/xsd/archimate/3.1/archimate3_Diagram.xsd';

export function childElements(el: Element): Element[] {
  const out: Element[] = [];
  for (let c = el.firstElementChild; c; c = c.nextElementSibling) out.push(c);
  return out;
}

function hasText(el: Element): boolean {
  for (let n = el.firstChild; n; n = n.nextSibling) {
    if ((n.nodeType === 3 || n.nodeType === 4) && n.nodeValue?.trim()) return true;
  }
  return false;
}

/**
 * Removes whitespace-only text from element-only content, recursively. Elements with real text
 * (names, labels) are left untouched. The exporter's indent pass is the inverse, so preserved
 * XML is stable across import -> export -> import.
 */
export function stripIndentation(el: Element): void {
  if (!hasText(el)) {
    for (let n = el.firstChild; n;) {
      const next = n.nextSibling;
      if (n.nodeType === 3 || n.nodeType === 8) el.removeChild(n); // whitespace text, comments
      n = next;
    }
  }
  for (const c of childElements(el)) stripIndentation(c);
}

function stripNamespaceDecls(el: Element): void {
  for (const a of Array.from(el.attributes)) {
    if (a.namespaceURI === XMLNS_NS) el.removeAttributeNode(a);
  }
  for (const c of childElements(el)) stripNamespaceDecls(c);
}

/** Serializes an unrecognized element. Namespace declarations are regenerated by the serializer. */
export function serializePreserved(el: Element): string {
  const clone = el.cloneNode(true) as Element;
  stripIndentation(clone);
  stripNamespaceDecls(clone);
  return new XMLSerializer().serializeToString(clone);
}

export function indent(el: Element, depth = 0): void {
  if (!el.firstElementChild || hasText(el)) return;
  const doc = el.ownerDocument;
  for (let n = el.firstChild; n;) {
    const next = n.nextSibling;
    if (n.nodeType === 3) el.removeChild(n);
    n = next;
  }
  const pad = '\n' + '  '.repeat(depth + 1);
  for (const c of childElements(el)) {
    el.insertBefore(doc.createTextNode(pad), c);
    indent(c, depth + 1);
  }
  el.appendChild(doc.createTextNode('\n' + '  '.repeat(depth)));
}

/** Collects unrecognized attributes and child elements while an owner is being read. */
export class ExtraBuilder {
  private attrs: PreservedAttr[] = [];
  private children: PreservedChild[] = [];
  private xsiType: string | null | undefined;

  attributes(el: Element, known: ReadonlySet<string>): void {
    for (const a of Array.from(el.attributes)) {
      if (a.namespaceURI === XMLNS_NS) continue;
      if (a.namespaceURI === XSI_NS && a.localName === 'type') continue;
      if (a.namespaceURI === null && known.has(a.localName)) continue;
      this.attrs.push({ ns: a.namespaceURI, name: a.name, value: a.value });
    }
  }

  child(after: string | null, el: Element): void {
    this.children.push({ after, xml: serializePreserved(el) });
  }

  setXsiType(t: string | null | undefined): void {
    this.xsiType = t;
  }

  build(): PreservedXml | undefined {
    const x: PreservedXml = {};
    if (this.attrs.length) x.attrs = this.attrs;
    if (this.children.length) x.children = this.children;
    if (this.xsiType !== undefined) x.xsiType = this.xsiType;
    return Object.keys(x).length ? x : undefined;
  }
}

/**
 * Walks `el`'s children: archimate-namespace children with a handler are consumed (a handler may
 * return false to decline); everything else goes to `extra`, anchored to the last consumed name.
 */
export function readChildren(
  el: Element,
  handlers: Record<string, (c: Element) => boolean | void>,
  extra: ExtraBuilder,
): void {
  let last: string | null = null;
  for (const c of childElements(el)) {
    const h =
      c.namespaceURI === NS && Object.hasOwn(handlers, c.localName)
        ? handlers[c.localName]
        : undefined;
    if (h && h(c) !== false) last = c.localName;
    else extra.child(last, c);
  }
}

/** Local part of an xsi:type QName value. */
export function xsiTypeOf(el: Element): string | null {
  const v = el.getAttributeNS(XSI_NS, 'type');
  if (v === null || (v === '' && !el.hasAttributeNS(XSI_NS, 'type'))) return null;
  const i = v.indexOf(':');
  return i >= 0 ? v.slice(i + 1) : v;
}

export function langOf(el: Element): string {
  return el.getAttributeNS(XML_NS, 'lang') ?? '';
}
